// Generator strips non-alphanumerics, so bytes that spell a name only once the
// gaps are removed must not match.
func TestScatteredBytesDoNotSpliceIntoAGenerator(t *testing.T) {
	manifest := []byte("c\x00l\x00a\x00u\x00d\x00e\x00")
	data := insertPNGChunk(t, basePNG(t), "caBX", manifest)

	for _, f := range Inspect(data).Findings {
		if f.Kind == C2PA && f.Value != "" {
			t.Errorf("scattered bytes matched: %q", f.Value)
		}
	}
}

func TestStripPNGPreservesTrailingBytes(t *testing.T) {
	trailer := []byte("TRAILING-DATA")
	data := insertPNGChunk(t, basePNG(t), "caBX", []byte("jumbc2pa manifest"))
	data = append(data, trailer...)

	out, changed, err := Strip(data, onlyKind(C2PA))
	if err != nil || !changed {
		t.Fatalf("Strip: changed=%v err=%v", changed, err)
	}
	if kindsOf(Inspect(out))[C2PA] {
		t.Error("C2PA survived the strip")
	}
	if !bytes.HasSuffix(out, trailer) {
		t.Errorf("trailing bytes dropped: out ends %q", out[max(0, len(out)-len(trailer)):])
	}
}

