func basePNG(t *testing.T) []byte {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, 2, 2))
	img.Set(0, 0, color.RGBA{R: 255, A: 255})
	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func baseJPEG(t *testing.T) []byte {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, 8, 8))
	var buf bytes.Buffer
	if err := jpeg.Encode(&buf, img, nil); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

// insertPNGChunk places a chunk immediately before IEND, where ancillary chunks
// legally live.
func insertPNGChunk(t *testing.T, data []byte, typ string, payload []byte) []byte {
	t.Helper()
	iend := bytes.LastIndex(data, []byte("IEND"))
	if iend < 4 {
		t.Fatal("no IEND in fixture")
	}
	at := iend - 4

	chunk := make([]byte, 0, len(payload)+12)
	chunk = binary.BigEndian.AppendUint32(chunk, uint32(len(payload)))
	chunk = append(chunk, typ...)
	chunk = append(chunk, payload...)
	chunk = binary.BigEndian.AppendUint32(chunk, crc32.ChecksumIEEE(append([]byte(typ), payload...)))

	out := make([]byte, 0, len(data)+len(chunk))
	out = append(out, data[:at]...)
	out = append(out, chunk...)
	return append(out, data[at:]...)
}

// insertJPEGSegment places a segment straight after SOI.
func insertJPEGSegment(t *testing.T, data []byte, marker byte, payload []byte) []byte {
	t.Helper()
	seg := []byte{0xFF, marker}
	seg = binary.BigEndian.AppendUint16(seg, uint16(len(payload)+2))
	seg = append(seg, payload...)

	out := make([]byte, 0, len(data)+len(seg))
	out = append(out, data[:2]...)
	out = append(out, seg...)
	return append(out, data[2:]...)
}

func kindsOf(r Report) map[Kind]bool {
	out := map[Kind]bool{}
	for _, f := range r.Findings {
		out[f.Kind] = true
	}
	return out
}

func onlyKind(k Kind) func(Finding) bool {
	return func(f Finding) bool { return f.Kind == k }
}

func everyRecord(Finding) bool { return true }

func TestDetectFormats(t *testing.T) {
	if got := Detect(basePNG(t)); got != FormatPNG {
		t.Errorf("png detected as %q", got)
	}
	if got := Detect(baseJPEG(t)); got != FormatJPEG {
		t.Errorf("jpeg detected as %q", got)
	}
	if got := Detect([]byte("just text")); got != FormatUnknown {
		t.Errorf("text detected as %q", got)
	}
}

