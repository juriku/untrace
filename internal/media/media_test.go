func TestManifestNamesItsGenerator(t *testing.T) {
	manifest := append([]byte("jumbc2pa\x00\x01claim_generator"), 0x71)
	manifest = append(manifest, "Claude 3.5 Sonnet"...)
	data := insertPNGChunk(t, basePNG(t), "caBX", manifest)

	var got Finding
	for _, f := range Inspect(data).Findings {
		if f.Kind == C2PA {
			got = f
		}
	}
	if got.Value != "claude" {
		t.Errorf("value = %q, want the generator it names", got.Value)
	}
	if _, ok := provenance.Generator(got.Value); !ok {
		t.Error("the reported value does not name a generator")
	}
}

