func TestPNGC2PADetectedAndStripped(t *testing.T) {
	data := insertPNGChunk(t, basePNG(t), "caBX", []byte("jumbc2pa manifest store"))

	if !kindsOf(Inspect(data))[C2PA] {
		t.Fatal("caBX chunk not reported as C2PA")
	}

	out, changed, err := Strip(data, onlyKind(C2PA))
	if err != nil || !changed {
		t.Fatalf("Strip: changed=%v err=%v", changed, err)
	}
	if kindsOf(Inspect(out))[C2PA] {
		t.Error("C2PA still present after strip")
	}

	// The point of stripping metadata is that the image survives it.
	if _, err := png.Decode(bytes.NewReader(out)); err != nil {
		t.Errorf("stripped png no longer decodes: %v", err)
	}
}

func TestPNGTextChunkReportsKeywordAndValue(t *testing.T) {
	payload := append([]byte("Software"), 0)
	payload = append(payload, []byte("Some Image Generator 1.0")...)
	data := insertPNGChunk(t, basePNG(t), "tEXt", payload)

	r := Inspect(data)
	if len(r.Findings) != 1 {
		t.Fatalf("got %d findings, want 1", len(r.Findings))
	}
	f := r.Findings[0]
	if f.Kind != PNGText || f.Label != "Software" || f.Value != "Some Image Generator 1.0" {
		t.Errorf("got %+v", f)
	}
}

