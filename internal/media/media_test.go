func TestStripOnlyRequestedKinds(t *testing.T) {
	data := insertJPEGSegment(t, baseJPEG(t), 0xFE, []byte("a comment"))
	data = insertJPEGSegment(t, data, 0xEB, []byte("jumbc2pa"))

	out, _, err := Strip(data, onlyKind(C2PA))
	if err != nil {
		t.Fatal(err)
	}
	got := kindsOf(Inspect(out))
	if got[C2PA] {
		t.Error("C2PA survived")
	}
	if !got[JPEGComment] {
		t.Error("comment was removed but was not requested")
	}
}

func TestStripSelectsRecordsNotKinds(t *testing.T) {
	data := insertPNGChunk(t, basePNG(t), "tEXt", []byte("Software\x00Adobe Firefly 3"))
	data = insertPNGChunk(t, data, "tEXt", []byte("Author\x00Jane Roe"))

	out, changed, err := Strip(data, func(f Finding) bool {
		return bytes.Contains([]byte(f.Value), []byte("Firefly"))
	})
	if err != nil || !changed {
		t.Fatalf("Strip: changed=%v err=%v", changed, err)
	}

	var survivors []Finding
	for _, f := range Inspect(out).Findings {
		if f.Kind == PNGText {
			survivors = append(survivors, f)
		}
	}
	if len(survivors) != 1 {
		t.Fatalf("got %d text chunks, want 1: %+v", len(survivors), survivors)
	}
	if survivors[0].Label != "Author" {
		t.Errorf("kept %q, want the record naming no generator", survivors[0].Label)
	}
}

